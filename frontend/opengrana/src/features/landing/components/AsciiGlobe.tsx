const LAND_ROWS = LANDMASK.split('\n')
const MASK_HEIGHT = LAND_ROWS.length
const MASK_WIDTH = LAND_ROWS[0].length

export function AsciiGlobe({ className }: { className?: string }) {
  const ref = useRef<HTMLPreElement>(null)

  useEffect(() => {
    const element = ref.current
    if (!element) return

    const screen = new Array<string>(SIZE * SIZE)
    const zbuffer = new Float64Array(SIZE * SIZE)
    const center = SIZE / 2
    const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches

    let angleA = 0
    let angleB = 0
    let frameId = 0
    let inView = true

    const renderFrame = () => {
      screen.fill(' ')
      zbuffer.fill(0)

      const cosA = Math.cos(angleA)
      const sinA = Math.sin(angleA)
      const cosB = Math.cos(angleB)
      const sinB = Math.sin(angleB)

      for (let theta = 0; theta <= Math.PI; theta += D_THETA) {
        const sinT = Math.sin(theta)
        const cosT = Math.cos(theta)
        // Latitude depende só de theta (eixo polar = Y).
        const maskRow = LAND_ROWS[
          Math.min(MASK_HEIGHT - 1, Math.floor((theta / Math.PI) * MASK_HEIGHT))
        ]

        for (let phi = 0; phi < TAU; phi += D_PHI) {
          const sinP = Math.sin(phi)
          const cosP = Math.cos(phi)

          // Ponto na esfera unitária (polos no eixo vertical).
          const x = sinT * cosP
          const y = cosT
          const z = sinT * sinP

          // Giro em torno do eixo vertical.
          const x1 = x * cosB + z * sinB
          const z1 = -x * sinB + z * cosB
          const y1 = y

          // Inclinação em torno do eixo horizontal.
          const y2 = y1 * cosA - z1 * sinA
          const z2 = y1 * sinA + z1 * cosA
          const x2 = x1

          if (z2 >= 0) continue // face traseira

          const ooz = 1 / (z2 + K2)
          const xp = Math.floor(center + K4 * ooz * x2)
          const yp = Math.floor(center - K4 * ooz * y2 * ASPECT)
          if (xp < 0 || xp >= SIZE || yp < 0 || yp >= SIZE) continue

          const index = xp + yp * SIZE
          if (ooz <= zbuffer[index]) continue
          zbuffer[index] = ooz

          const luminance = x2 * LIGHT[0] + y2 * LIGHT[1] + z2 * LIGHT[2]
          const clamped = Math.max(0, Math.min(1, luminance))

          // Longitude depende só de phi.
          const longitude = phi > Math.PI ? phi - TAU : phi
          const maskCol = Math.min(
            MASK_WIDTH - 1,
            Math.floor(((longitude + Math.PI) / TAU) * MASK_WIDTH),
          )
          const [low, high] = maskRow[maskCol] === '#' ? LAND_RANGE : OCEAN_RANGE
          const shade = low + Math.round(clamped * (high - low))

          screen[index] = RAMP[shade]
        }
      }

      let output = ''
      for (let row = 0; row < SIZE; row += 1) {
        output += `${screen.slice(row * SIZE, row * SIZE + SIZE).join('')}\n`
      }
      element.textContent = output
    }

    const loop = () => {
      renderFrame()
      if (!reducedMotion) {
        angleA += TILT
        angleB += SPIN
      }
      frameId = window.requestAnimationFrame(loop)
    }

    if (reducedMotion) {
      renderFrame()
    } else {
      frameId = window.requestAnimationFrame(loop)
    }

    let observer: IntersectionObserver | undefined
    if (!reducedMotion && typeof IntersectionObserver !== 'undefined') {
      observer = new IntersectionObserver(([entry]) => {
        const nextInView = entry.isIntersecting
        if (nextInView === inView) return
        inView = nextInView
        if (inView) {
          frameId = window.requestAnimationFrame(loop)
        } else {
          window.cancelAnimationFrame(frameId)
        }
      })
      observer.observe(element)
    }

    return () => {
      observer?.disconnect()
      window.cancelAnimationFrame(frameId)
    }
  }, [])

  return (
    <pre
      ref={ref}
      aria-hidden="true"
      className={cn(
        'pointer-events-none select-none font-mono font-normal text-primary [line-height:1]',
        className,
      )}
    />
  )
}
