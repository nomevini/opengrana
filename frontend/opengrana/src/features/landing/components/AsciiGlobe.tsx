import { useEffect, useRef } from 'react'

import { cn } from '@/shared/lib/utils'

// Rampa de densidade: do mais "escuro/fino" ao mais "claro/grosso".
const RAMP = '.,-~:;=!*#$@'
const TAU = Math.PI * 2

const SIZE = 200 // grid de caracteres (SIZE x SIZE)
const K2 = 5 // distância da câmera
const K4 = SIZE * 2.05 // escala da projeção
const ASPECT = 0.55 // compensa a largura da célula de caractere (~0.55em)
const D_THETA = 0.02
const D_PHI = 0.02
const SPIN = 0.005 // giro em torno do eixo vertical
const TILT = 0.0012 // inclinação em torno do eixo horizontal

// Faixas da rampa com um vão entre elas: oceano bem mais "ralo",
// terra bem mais "densa", para os continentes saltarem aos olhos.
const OCEAN_RANGE: [number, number] = [0, 4]
const LAND_RANGE: [number, number] = [7, RAMP.length - 1]

// Direção da luz (espaço da câmera).
const LIGHT = (() => {
  const [x, y, z] = [-0.45, 0.62, -0.65]
  const length = Math.hypot(x, y, z)
  return [x / length, y / length, z / length]
})()

